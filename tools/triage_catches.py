#!/usr/bin/env python3
"""Generate a conservative catch-site inventory for Nostrodomus.

This tool is read-only. It does not decide code changes by itself; it creates the
Priority 2 work queue so consequential catch sites can be instrumented in small,
reviewable patches instead of mass-edited blindly.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / "src" / "main.legacy.js"
REPORT = ROOT / "reports" / "CATCH_TRIAGE.md"

CONSEQUENTIAL_TOKENS = [
    "provider", "provide", "canHandle", "loadSettings", "saveSettings", "JSON.parse", "localStorage",
    "buildIndex", "score", "candidate", "completion", "insert", "dispatch", "yaml", "context",
    "diagnostic", "exportDiagnostics", "clipboard", "hass", "runtime", "library", "settings",
]
IDEMPOTENCE_TOKENS = [
    "disconnect", "remove", "cancelAnimationFrame", "clearTimeout", "clearInterval", "takeRecords",
    "dataset", "style", "classList", "removeAttribute", "setAttribute", "querySelector", "appendChild",
    "focus", "blur", "delete W", "popover", "showPopover", "hidePopover",
]

@dataclass
class CatchSite:
    index: int
    line: int
    binding: str
    classification: str
    reason: str
    body_preview: str
    context_preview: str


def line_for(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def find_matching_brace(text: str, open_pos: int) -> int:
    depth = 0
    in_string: str | None = None
    escaped = False
    in_line_comment = False
    in_block_comment = False
    i = open_pos
    while i < len(text):
        ch = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""
        if in_line_comment:
            if ch == "\n":
                in_line_comment = False
            i += 1
            continue
        if in_block_comment:
            if ch == "*" and nxt == "/":
                in_block_comment = False
                i += 2
                continue
            i += 1
            continue
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == in_string:
                in_string = None
            i += 1
            continue
        if ch == "/" and nxt == "/":
            in_line_comment = True
            i += 2
            continue
        if ch == "/" and nxt == "*":
            in_block_comment = True
            i += 2
            continue
        if ch in {'"', "'", "`"}:
            in_string = ch
            i += 1
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(text) - 1


def compact(value: str, limit: int = 180) -> str:
    text = re.sub(r"\s+", " ", value).strip()
    return text[: limit - 1] + "…" if len(text) > limit else text


def classify(binding: str, body: str, context: str) -> tuple[str, str]:
    haystack = f"{binding}\n{body}\n{context}"
    if any(token in haystack for token in CONSEQUENTIAL_TOKENS):
        return "B", "consequential runtime/settings/provider/context/diagnostics path"
    if not body.strip():
        return "A", "empty cleanup/idempotence guard"
    if any(token in haystack for token in IDEMPOTENCE_TOKENS):
        return "A", "cleanup, DOM/style idempotence, or teardown guard"
    return "REVIEW", "manual review required before deciding A/B"


def inventory(text: str) -> list[CatchSite]:
    sites: list[CatchSite] = []
    pattern = re.compile(r"catch\s*(?:\(([^)]*)\))?\s*\{")
    for idx, match in enumerate(pattern.finditer(text), start=1):
        open_pos = match.end() - 1
        close_pos = find_matching_brace(text, open_pos)
        body = text[open_pos + 1:close_pos]
        context = text[max(0, match.start() - 420):min(len(text), close_pos + 260)]
        binding = (match.group(1) or "").strip()
        classification, reason = classify(binding, body, context)
        sites.append(CatchSite(
            index=idx,
            line=line_for(text, match.start()),
            binding=binding or "<none>",
            classification=classification,
            reason=reason,
            body_preview=compact(body),
            context_preview=compact(context),
        ))
    return sites


def write_report(sites: list[CatchSite], path: Path) -> None:
    counts: dict[str, int] = {}
    for site in sites:
        counts[site.classification] = counts.get(site.classification, 0) + 1
    lines = [
        "# Priority 2 Catch Triage",
        "",
        "Generated by `python3 tools/triage_catches.py --write`.",
        "",
        "This is a conservative inventory, not a blanket edit plan. `A` sites are cleanup/idempotence guards. `B` sites are consequential paths that should be routed through `recordRuntimeError(scope, err, detail)` in focused patches. `REVIEW` sites need manual review before conversion.",
        "",
        "## Summary",
        "",
        f"- Total catch sites: {len(sites)}",
        f"- A cleanup/idempotence: {counts.get('A', 0)}",
        f"- B consequential: {counts.get('B', 0)}",
        f"- REVIEW manual: {counts.get('REVIEW', 0)}",
        "",
        "## Inventory",
        "",
        "| # | Line | Binding | Class | Reason | Body preview |",
        "|---:|---:|---|---|---|---|",
    ]
    for site in sites:
        body = site.body_preview.replace("|", "\\|") or "empty"
        lines.append(f"| {site.index} | {site.line} | `{site.binding}` | {site.classification} | {site.reason} | `{body}` |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Inventory catch sites in src/main.legacy.js")
    parser.add_argument("--json", action="store_true", help="print JSON instead of text summary")
    parser.add_argument("--write", action="store_true", help="write reports/CATCH_TRIAGE.md")
    args = parser.parse_args()

    text = RUNTIME.read_text(encoding="utf-8", errors="replace")
    sites = inventory(text)
    if args.write:
        write_report(sites, REPORT)
    counts: dict[str, int] = {}
    for site in sites:
        counts[site.classification] = counts.get(site.classification, 0) + 1
    result = {"ok": True, "total": len(sites), "counts": counts, "report": str(REPORT.relative_to(ROOT))}
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(f"Catch triage: total={len(sites)} A={counts.get('A', 0)} B={counts.get('B', 0)} REVIEW={counts.get('REVIEW', 0)}")
        if args.write:
            print(f"Report: {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
