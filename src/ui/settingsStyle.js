export function ensureDistinctSyntaxPalette(palette, theme) {
  const out = { ...palette };
  const seen = new Map();
  STYLE_SYNTAX_KIND_ORDER.forEach((kind, index) => {
    const raw = String(out[kind] || DARKPLUS_SYNTAX_COLORS[kind] || DARKPLUS_SYNTAX_COLORS.fg);
    const key = raw.toLowerCase().replace(/\s+/g, "");
    if (seen.has(key)) {
      out[kind] = syntaxHsl(theme, (index * 5) - 42, (index % 5) - 2, 0.04);
    }
    seen.set(String(out[kind]).toLowerCase().replace(/\s+/g, ""), kind);
  });
  return out;
}

export function syntaxThemePalette(theme, saturationMultiplier = 1) {
  // Apply the saturation slider EXACTLY ONCE, in the closing map below, so it scales generated
  // (syntaxHsl) and Classic (hardcoded hex) tokens identically. Previously the multiplier was also
  // baked into `t` and re-applied inside every syntaxHsl call, so generated themes desaturated ~2.4x
  // too steeply as the slider moved off 1.0 (and inconsistently with Classic). `t` no longer carries
  // it, so syntaxHsl uses its default 1; at the default slider of 1 the output is byte-identical.
  const boost = clampNumber(saturationMultiplier, 0.35, 1.85, 1);
  const t = { ...(theme || STYLE_SYNTAX_PRESETS.vscodeDarkPlus) };
  const isDarkPlus = theme === STYLE_SYNTAX_PRESETS.vscodeDarkPlus || (t.label || "") === "Classic";
  // Push every token's lightness AWAY from the editor background (brighter on dark
  // themes, darker on light themes) by an emphasis rank, so tokens stay readable and
  // separate by lightness within the tight hue band.
  const isLight = (t.lightness ?? 64) < 50;
  const ld = isLight ? -1 : 1;
  const bs = isLight ? 0.62 : 1;
  const palette = isDarkPlus
    ? {
        fg: t.fg || DARKPLUS_SYNTAX_COLORS.fg,
        dim: t.dim || DARKPLUS_SYNTAX_COLORS.dim,
        comment: t.comment || DARKPLUS_SYNTAX_COLORS.comment,
        key: "#9cdcfe",
        yamlList: "#dcdcaa",
        string: "#ce9178",
        number: "#b5cea8",
        bool: "#569cd6",
        keyword: "#c586c0",
        filter: "#dcdcaa",
        jinja: "#c586c0",
        cssSelector: "#d7ba7d",
        cssProp: "#9cdcfe",
        cssValue: "#ce9178",
        cssGlow: "#4ec9b0",
        cssDim: "#808080",
        punct: "#d4d4d4",
        op: "#d4d4d4",
      }
    : ensureDistinctSyntaxPalette({
        // Tokens fan out within a tight band (~+-44 deg) of the theme's baseHue so every
        // theme reads as one coherent color family that matches its name -- no cross-wheel
        // hues (a "Mocha" theme is all warm, never purple/green). Token separation comes
        // from lightness/saturation spread, not from opposite hues.
        fg: t.fg || DARKPLUS_SYNTAX_COLORS.fg,
        dim: t.dim || syntaxHsl(t, -38, ld * 4 * bs, -0.22),
        comment: t.comment || syntaxHsl(t, -26, ld * 2 * bs, -0.30),
        key: syntaxHsl(t, -36, ld * 21 * bs, 0.06),
        yamlList: syntaxHsl(t, -44, ld * 24 * bs, 0.06),
        string: syntaxHsl(t, -18, ld * 9 * bs, 0.02),
        number: syntaxHsl(t, -4, ld * 26 * bs, -0.03),
        bool: syntaxHsl(t, 12, ld * 17 * bs, 0.10),
        keyword: syntaxHsl(t, 30, ld * 13 * bs, 0.12),
        filter: syntaxHsl(t, 38, ld * 15 * bs, 0.04),
        jinja: syntaxHsl(t, 44, ld * 19 * bs, 0.10),
        cssSelector: syntaxHsl(t, -30, ld * 5 * bs, 0.05),
        cssProp: syntaxHsl(t, -12, ld * 11 * bs, 0.00),
        cssValue: syntaxHsl(t, 2, ld * 7 * bs, 0.03),
        cssGlow: syntaxHsl(t, 16, ld * 22 * bs, 0.14),
        cssDim: syntaxHsl(t, 30, ld * 3 * bs, -0.16),
        punct: syntaxHsl(t, -8, ld * 1 * bs, -0.30),
        op: syntaxHsl(t, 14, ld * 10 * bs, 0.02),
      }, t);
  return Object.fromEntries(Object.entries(palette).map(([kind, color]) => [kind, syntaxColorWithSaturation(color, boost)]));
}

export function syntaxThemeOptions(presets = STYLE_SYNTAX_PRESETS) {
  return Object.entries(presets).map(([key, preset]) => ({ key, label: preset.label || key }));
}

export function resolveSyntaxTintSettings(settings = {}, defaultStyle = {}) {
  const presetKey = settings.syntaxTintPreset || defaultStyle.syntaxTintPreset || "vscodeDarkPlus";
  const preset = STYLE_SYNTAX_PRESETS[presetKey] || STYLE_SYNTAX_PRESETS.vscodeDarkPlus;
  const active = settings.syntaxTintEnabled !== false;
  return {
    presetKey: STYLE_SYNTAX_PRESETS[presetKey] ? presetKey : "vscodeDarkPlus",
    label: preset.label || presetKey,
    active,
    hue: preset.baseHue ?? defaultStyle.syntaxTintHue,
    saturation: preset.saturation ?? defaultStyle.syntaxTintSaturation,
    opacity: clampNumber(settings.syntaxTintOpacity, 0, 0.75, defaultStyle.syntaxTintOpacity),
    themeOpacity: clampNumber(settings.syntaxThemeOpacity, 0.35, 1, defaultStyle.syntaxThemeOpacity),
    themeSaturation: clampNumber(settings.syntaxThemeSaturation, 0.35, 1.85, defaultStyle.syntaxThemeSaturation),
    filterBase: preset.baseHue ?? 210,
    palette: syntaxThemePalette(preset, settings.syntaxThemeSaturation),
    textShadow: active && preset.glow
      ? `0 0 7px ${hslaFromHue(preset.baseHue ?? 210, (preset.saturation ?? 1) * clampNumber(settings.syntaxThemeSaturation, 0.35, 1.85, defaultStyle.syntaxThemeSaturation), 66, Math.min(0.18, preset.glow))}`
      : "none",
  };
}

export function syntaxColorWithOpacity(color, opacity = 1) {
  return syntaxColorWithOpacityCore(color, opacity, DARKPLUS_SYNTAX_COLORS.fg);
}
