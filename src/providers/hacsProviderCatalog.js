export const MAIN_PROVIDER_SURFACE_IDS = Object.freeze(MAIN_PROVIDER_SURFACES.map((surface) => surface.id));

export function normalizeProviderSurfaceId(value) {
  return String(value ?? "").trim().toLowerCase().replace(/[_\s]+/g, "-");
}

export function normalizeProviderCardType(value) {
  return String(value ?? "")
    .trim()
    .replace(/^['"]|['"]$/g, "")
    .toLowerCase()
    .replace(/[_\s]+/g, "-");
}

function catalogLookupMap(entries) {
  const map = Object.create(null);
  for (const [key, surface] of entries) {
    const normalized = normalizeProviderSurfaceId(key);
    if (normalized && !map[normalized]) map[normalized] = surface;
  }
  return Object.freeze(map);
}

function catalogCardTypeMap() {
  const map = Object.create(null);
  for (const surface of MAIN_PROVIDER_SURFACES) {
    for (const cardType of surface.cardTypes || []) {
      const normalized = normalizeProviderCardType(cardType);
      if (normalized && !map[normalized]) map[normalized] = surface;
    }
  }
  return Object.freeze(map);
}

const MAIN_PROVIDER_SURFACE_LOOKUP = catalogLookupMap(
  MAIN_PROVIDER_SURFACES.flatMap((surface) => [
    [surface.id, surface],
    ...(surface.aliases || []).map((alias) => [alias, surface]),
  ])
);

const MAIN_PROVIDER_CARD_TYPE_LOOKUP = catalogCardTypeMap();

export function getProviderSurface(id) {
  return MAIN_PROVIDER_SURFACE_LOOKUP[normalizeProviderSurfaceId(id)] || null;
}

export function getProviderSurfaceByCardType(cardType) {
  return MAIN_PROVIDER_CARD_TYPE_LOOKUP[normalizeProviderCardType(cardType)] || null;
}

export function providerSurfacesForLane(laneId) {
  const normalized = String(laneId ?? "").trim().toLowerCase();
  return Object.freeze(MAIN_PROVIDER_SURFACES.filter((surface) => surface.lanes.includes(normalized)));
}

export function providerSurfacesForFamily(family) {
  const normalized = String(family ?? "").trim().toLowerCase();
  return Object.freeze(MAIN_PROVIDER_SURFACES.filter((surface) => surface.providerFamilies.includes(normalized)));
}

export function hacsProviderCatalogStatus() {
  const byLane = Object.create(null);
  const byCategory = Object.create(null);
  for (const surface of MAIN_PROVIDER_SURFACES) {
    byCategory[surface.category] = (byCategory[surface.category] || 0) + 1;
    for (const lane of surface.lanes) byLane[lane] = (byLane[lane] || 0) + 1;
  }
  return Object.freeze({
    ok: true,
    stage: HACS_PROVIDER_CATALOG_STAGE,
    catalogVersion: HACS_PROVIDER_CATALOG_VERSION,
    surfaceCount: MAIN_PROVIDER_SURFACES.length,
    surfaceIds: MAIN_PROVIDER_SURFACE_IDS.slice(),
    byLane: Object.freeze({ ...byLane }),
    byCategory: Object.freeze({ ...byCategory }),
    requiredSurfacesPresent: MAIN_PROVIDER_SURFACE_IDS.length >= 20 && MAIN_PROVIDER_SURFACE_IDS.every((id) => Boolean(getProviderSurface(id))),
    registersProviders: false,
    drivesAutocomplete: false,
    opensPopup: false,
    insertsText: false,
  });
}
